// Imports the SaaS-Sentry icon set (Phosphor Icons, MIT) into a TypeScript module of path data.
//
//   node scripts/import-icons.mjs <icon-folder>
//
// The folder holds `duotone/` and `fill/` sub-folders of 256x256 SVG files. SVG files are external input, so no
// SVG is bundled or parsed at runtime: each file must match one strict shape (an <svg> with only <path d="…">
// children and an optional 0.2 opacity), and only the numeric path data is written out. Anything else fails.
import fs from 'node:fs'
import path from 'node:path'

const source = process.argv[2]
if (!source) throw new Error('Usage: node scripts/import-icons.mjs <icon-folder>')

const variants = ['duotone', 'fill']
const header = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" fill="currentColor">'
const pathPattern = /^<path d="([MmLlHhVvCcSsQqTtAaZz0-9.,\- ]{1,8000})"( opacity="0\.2")?\/>/
const namePattern = /^[a-z][a-z0-9-]{0,40}$/

function parse(file) {
  let rest = fs.readFileSync(file, 'utf8').trim()
  if (!rest.startsWith(header) || !rest.endsWith('</svg>')) throw new Error(`Unexpected SVG wrapper: ${file}`)
  rest = rest.slice(header.length, -'</svg>'.length)
  const paths = []
  while (rest.length) {
    const match = pathPattern.exec(rest)
    if (!match) throw new Error(`Unexpected SVG content: ${file}`)
    paths.push(match[2] ? { d: match[1], opacity: 0.2 } : { d: match[1] })
    rest = rest.slice(match[0].length)
  }
  if (!paths.length || paths.length > 4) throw new Error(`Unexpected path count: ${file}`)
  return paths
}

const icons = {}
for (const variant of variants) {
  const folder = path.join(source, variant)
  for (const entry of fs.readdirSync(folder).sort()) {
    if (!entry.endsWith('.svg')) continue
    const name = entry.slice(0, -4)
    if (!namePattern.test(name)) throw new Error(`Unexpected icon name: ${entry}`)
    icons[name] ??= {}
    icons[name][variant] = parse(path.join(folder, entry))
  }
}
const names = Object.keys(icons).sort()
for (const name of names) {
  for (const variant of variants) if (!icons[name][variant]) throw new Error(`Missing ${variant} for ${name}`)
}

const body = names
  .map((name) => {
    const entries = variants
      .map(
        (variant) =>
          `    ${variant}: ${JSON.stringify(icons[name][variant]).replaceAll('"d":', 'd:').replaceAll('"opacity":', 'opacity:')}`
      )
      .join(',\n')
    return `  '${name}': {\n${entries}\n  }`
  })
  .join(',\n')

const out = `// Generated by scripts/import-icons.mjs. Do not edit by hand.
// Icons from Phosphor Icons (https://phosphoricons.com), MIT License, Copyright (c) 2023 Phosphor Icons.
// 256x256 view box; drawn with the current color, duotone back layers at 0.2 opacity.

export interface SaasIconPath {
  d: string
  opacity?: number
}

export const saasIcons = {
${body}
} as const satisfies Record<string, Record<'duotone' | 'fill', readonly SaasIconPath[]>>

export type SaasIconName = keyof typeof saasIcons
`
fs.writeFileSync('src/shared/ui/saas-icons.generated.ts', out)
console.log(`Imported ${names.length} icons`)
